#!/usr/bin/env node
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const [ref = "main", ...rest] = process.argv.slice(2);
assert.equal(
  rest.length,
  0,
  "Usage: node scripts/sync-buzz-kinds.mjs [block/buzz ref]",
);

const source = "crates/buzz-core/src/kind.rs";
const fixture = new URL(
  "../src-tauri/src/credential_service/buzz_kinds.txt",
  import.meta.url,
);
const outsideAllKinds = ["KIND_AUTH"];

const gh = (...args) =>
  execFileSync("gh", args, { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 });

const sha = gh("api", `repos/block/buzz/commits/${ref}`, "--jq", ".sha").trim();
assert.match(sha, /^[0-9a-f]{40}$/);
const text = gh(
  "api",
  "-H",
  "Accept: application/vnd.github.raw",
  `repos/block/buzz/contents/${source}?ref=${sha}`,
);

const values = new Map(
  [...text.matchAll(/^pub const (\w+): u32 = ([\d_]+);/gm)].map(
    ([, name, value]) => [name, Number(value.replaceAll("_", ""))],
  ),
);
const list = text.match(/pub const ALL_KINDS: &\[u32\] = &\[([^\]]*)\];/);
assert.ok(list, "ALL_KINDS not found in kind.rs");
const names = [
  ...list[1].matchAll(/^\s*(\w+),/gm).map(([, name]) => name),
  ...outsideAllKinds,
];
assert.equal(new Set(names).size, names.length, "duplicate kind constant");

const rows = names
  .map((name) => {
    assert.ok(values.has(name), `${name} is not a literal u32 constant`);
    return [values.get(name), name];
  })
  .sort(([a], [b]) => a - b);

writeFileSync(
  fixture,
  [
    `# Generated by scripts/sync-buzz-kinds.mjs from block/buzz@${sha}`,
    `# ${source}: ALL_KINDS, plus ${outsideAllKinds.join(", ")} (signed by buzz-cli, absent from ALL_KINDS).`,
    ...rows.map(([kind, name]) => `${kind} ${name}`),
    "",
  ].join("\n"),
);
console.log(`${rows.length} kinds from block/buzz@${sha}`);
